// M0 HOST encoding fragment for the A530/Mesa A5xx sysmem path.
// No BO allocation, GPU transport, shader execution or hardware acceptance.
#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <string>
#include "hakios-metal/pm4.hpp"

namespace hakios::metal::render_a5xx {

enum class ColorFormat : uint32_t { RGBA8Unorm = 70, BGRA8Unorm = 80 };

struct ColorTarget {
    uint64_t address = 0, allocationBytes = 0;
    uint32_t width = 0, height = 0, pitchBytes = 0;
    uint64_t layerBytes = 0;
    ColorFormat format = ColorFormat::RGBA8Unorm;
    bool writable = true;
};

// A caller-owned, GPU-writable four-byte scratch range. Required by fd5's
// BLIT and CCU timestamp-form events, distinct from the color allocation.
// No CP_EVENT_WRITE TIMESTAMP bit is set: payload value is zero, like fd5.
struct Scratch { uint64_t address = 0, bytes = 0; bool writable = true; };
struct Rect { uint32_t x = 0, y = 0, width = 0, height = 0; }; // half-open
struct Viewport {
    float x = 0, y = 0, width = 0, height = 0, minDepth = 0, maxDepth = 1;
};

// One level/layer/sample, LINEAR UNORM only. Pitch is a multiple of 256 bytes,
// layer size a multiple of 4096 with height padded to 32 rows (fd5_layout.c).
// The BO/view may be larger. Address is a 64-aligned subview below 2^49.
// These are accepted host subset restrictions, not measured device limits.
bool validTarget(const ColorTarget& target, std::string* why = nullptr);

// Requires exclusive ownership of stream while active. It can sit between
// CommandBuffer pass begin/end; M3 will insert its A5xx program/linkage/VFD
// state into that same stream. Existing A6xx Program metadata is insufficient.
// BO lifetime/residency, MMU mapping, CPU coherency and eventual fence are the
// caller's responsibility. Scratch events alone are not completion evidence.
class SysmemPass {
public:
    explicit SysmemPass(pm4::Stream& stream, size_t maxWords = 1024 * 1024)
        : stream_(stream), maxWords_(maxWords) {}
    SysmemPass(const SysmemPass&) = delete;
    SysmemPass& operator=(const SysmemPass&) = delete;

    // A530 fixed restore + BYPASS sysmem prep, all eight MRT slots explicitly
    // set (one bound, seven disabled), depth/stencil/flags off, MSAA one,
    // full window/scissors and a Metal viewport (NDC y up, negative y scale).
    bool begin(const ColorTarget& target, const Scratch& scratch,
               std::string* why = nullptr);
    bool setViewport(const Viewport& viewport, std::string* why = nullptr);
    bool setScissor(const Rect& scissor, std::string* why = nullptr);
    // Full attachment clear, independent of viewport/scissor. Byte components
    // are exact UNORM8 logical RGBA values. Only encodes fd5 RB_CLEAR/BLIT.
    bool clearColor(const std::array<uint8_t, 4>& rgba, std::string* why = nullptr);
    bool end(std::string* why = nullptr);

    // Deliberately refuses until M3 supplies generation-tagged, linked A5xx
    // VS/FS footprints, varying linkage, FS outputs and vertex-fetch state.
    // No CP_DRAW_INDX_OFFSET or shader load is generated by this M0 module.
    bool drawTriangles(uint32_t firstVertex, uint32_t vertexCount,
                       std::string* why = nullptr);
    bool active() const { return active_; }
    const ColorTarget& target() const { return target_; }

    // Failed calls leave stream and pass state unchanged. maxWords applies to
    // the complete destination stream, including caller-inserted M3 packets.
private:
    bool append(const pm4::Stream& added, std::string* why);
    pm4::Stream& stream_;
    size_t maxWords_;
    bool active_ = false;
    ColorTarget target_;
    Scratch scratch_;
};

} // namespace hakios::metal::render_a5xx
